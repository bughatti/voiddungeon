----------------------------------------------------------------------
-- VoidDungeon — the dungeon journal WoW Forever doesn't have, inside VoidMap.
--
-- In a dungeon (or picked from the list) VoidMap's map area shows the dungeon's map
-- (Atlas's maps, numbered bosses you can click) and the side area gets tabs:
--   Quests  your quests for this dungeon
--   Loot    each boss's drops with drop chances (NorgannonDB)
--   Path    the way through: entrance, bosses in order (hover = spot on the map)
--   Tips    VoidCheatSheet's boss notes, when VoidCheatSheet is installed
--
-- Files: Data/Atlas.lua + Data/Loot.lua + Maps/*.blp are generated by
-- tools/cmd/vdungeon-seed. Canvas.lua = the map and toolbar, Side.lua = the tabs.
-- Credits: maps by the Atlas Team (GPL-2.0-or-later), loot from NorgannonDB
-- (GPL-3.0, built on Questie). VoidDungeon is GPL-3.0.
----------------------------------------------------------------------
local ADDON, ns = ...
VoidDungeon = VoidDungeon or {}
local J = VoidDungeon
ns.J = J

J.A = { 0, 0.78, 1 }
J.FONT = "Fonts\\FRIZQT__.TTF"
J.MAPS = "Interface\\AddOns\\" .. ADDON .. "\\Maps\\"

function J:Print(msg) DEFAULT_CHAT_FRAME:AddMessage("|cff00c7ff[VoidDungeon]|r " .. tostring(msg)) end

----------------------------------------------------------------------
-- Dungeons: Atlas maps grouped by dungeon
----------------------------------------------------------------------
-- "Wailing Caverns (Entrance)" / "Blackfathom DeepsMapB" / "Blackrock Mountain: Blackrock Depths"
-- -> the dungeon's name.
local function baseName(zone)
    local z = zone:gsub(" %(Entrance%)$", ""):gsub("Map[A-C]$", ""):gsub("^Blackrock Mountain: ", "")
    return z
end
J.baseName = baseName

local function norm(s)
    return (s or ""):lower():gsub("^the ", ""):gsub("[^%w]", "")
end

-- Instance names that differ from the map name (GetInstanceInfo -> our dungeon name).
local ALIAS = {
    [norm("The Stockade")] = "Stormwind Stockades",
    [norm("Stormwind Stockade")] = "Stormwind Stockades",
    [norm("Blackrock Spire")] = "Lower Blackrock Spire",
}

J.dungeons, J.byName = {}, {}

local function minLevel(lv) return tonumber((lv or ""):match("^(%d+)")) or 99 end

local function buildIndex()
    for key, m in pairs(ns.Atlas or {}) do
        local name = baseName(m.zone)
        local d = J.byName[name]
        if not d then
            d = { name = name, maps = {}, lv = m.lv, min = minLevel(m.lv), loc = m.loc }
            J.byName[name] = d
            J.dungeons[#J.dungeons + 1] = d
        end
        d.maps[#d.maps + 1] = key
        if minLevel(m.lv) < d.min then d.min, d.lv = minLevel(m.lv), m.lv end
    end
    for _, d in ipairs(J.dungeons) do
        -- entrance first, then A / B / C, then the rest by key
        table.sort(d.maps, function(a, b)
            local ea, eb = a:find("Ent$") ~= nil, b:find("Ent$") ~= nil
            if ea ~= eb then return ea end
            return a < b
        end)
        d.main = d.maps[1]
        for _, k in ipairs(d.maps) do
            if not k:find("Ent$") and ns.Atlas[k].img then d.main = k; break end
        end
    end
    table.sort(J.dungeons, function(a, b)
        if a.min ~= b.min then return a.min < b.min end
        return a.name < b.name
    end)
end

-- The dungeon you're standing in (by instance name), or nil.
function J:CurrentDungeon()
    local name, kind = GetInstanceInfo()
    if kind ~= "party" and kind ~= "raid" then return nil end
    local n = norm(name)
    local want = ALIAS[n]
    if want and J.byName[want] then return J.byName[want] end
    for _, d in ipairs(J.dungeons) do
        if norm(d.name) == n then return d end
    end
    for _, d in ipairs(J.dungeons) do   -- "Scarlet Monastery" -> its first wing
        if norm(d.name):sub(1, #n) == n then return d end
    end
    return nil
end

----------------------------------------------------------------------
-- Items (quality filter in game: Forever's own data is the truth)
----------------------------------------------------------------------
-- pending[id] = "asked" while the game loads it, "failed" if it couldn't: a failed item is
-- never asked for again this session (else fail -> refresh -> ask again loops; Astra review)
local pending, refreshQueued = {}, false

-- name, quality, icon of an item, or nil while the game is still loading it.
function J:Item(id)
    local name = C_Item.GetItemNameByID(id)
    local q = C_Item.GetItemQualityByID(id)
    if not (name and q) then
        if not pending[id] then
            pending[id] = "asked"
            C_Item.RequestLoadItemDataByID(id)
        end
        return nil
    end
    return name, q, C_Item.GetItemIconByID(id)
end

-- Worth showing in a guide: uncommon or better, or a quest item.
function J:Shown(id, q)
    if q and q >= 2 then return true end
    local classID = select(6, C_Item.GetItemInfoInstant(id))
    return classID == 12
end

-- A boss's loot: { {id, pct}, ... } highest chance first.
function J:Loot(npc)
    local flat = npc and ns.Loot and ns.Loot[npc]
    local out = {}
    if not flat then return out end
    for i = 1, #flat, 2 do out[#out + 1] = { flat[i], flat[i + 1] } end
    return out
end

----------------------------------------------------------------------
-- State + events
----------------------------------------------------------------------
J.cur = nil      -- the dungeon shown
J.map = nil      -- its map key shown
J.sel = nil      -- the legend row selected (a boss)

local listeners = {}
function J:OnChange(fn) listeners[#listeners + 1] = fn end
function J:Changed(what)
    for _, fn in ipairs(listeners) do
        local ok, err = pcall(fn, what)
        if not ok then geterrorhandler()(err) end
    end
end

function J:Show(d, mapKey)
    if not d then return end
    self.cur, self.map, self.sel = d, mapKey or d.main, nil
    self:Changed("dungeon")
end

function J:ShowMap(key)
    if not (self.cur and key and ns.Atlas[key]) then return end
    self.map, self.sel = key, nil
    self:Changed("map")
end

function J:Select(row)
    self.sel = row
    self:Changed("select")
end

local ev = CreateFrame("Frame")
ev:RegisterEvent("ADDON_LOADED")
ev:RegisterEvent("PLAYER_ENTERING_WORLD")
ev:RegisterEvent("GET_ITEM_INFO_RECEIVED")
ev:RegisterEvent("ITEM_DATA_LOAD_RESULT")      -- RequestLoadItemDataByID's own answer (Sol review)
ev:RegisterEvent("QUEST_LOG_UPDATE")
ev:SetScript("OnEvent", function(_, event, arg1, arg2)
    if event == "ADDON_LOADED" and arg1 == ADDON then
        VoidDungeonDB = VoidDungeonDB or {}
        buildIndex()
    elseif event == "PLAYER_ENTERING_WORLD" then
        local d = J:CurrentDungeon()
        J.inside = d
        if d then J:Show(d) elseif J.mode then J:Changed("zone") end
    elseif event == "GET_ITEM_INFO_RECEIVED" or event == "ITEM_DATA_LOAD_RESULT" then
        if arg1 and pending[arg1] == "asked" then
            if arg2 == false then pending[arg1] = "failed" return end
            pending[arg1] = nil
            if J.mode and not refreshQueued then
                refreshQueued = true
                C_Timer.After(0.3, function() refreshQueued = false; J:Changed("items") end)
            end
        end
    elseif event == "QUEST_LOG_UPDATE" then
        if J.mode then J:Changed("quests") end
    end
end)

SLASH_VOIDDUNGEON1 = "/vdn"
SLASH_VOIDDUNGEON2 = "/vdungeon"
SlashCmdList.VOIDDUNGEON = function(msg)
    msg = (msg or ""):lower():gsub("^%s+", ""):gsub("%s+$", "")
    if msg ~= "" then
        for _, d in ipairs(J.dungeons) do
            if d.name:lower():find(msg, 1, true) then J:Open(d); return end
        end
        J:Print("no dungeon matches \"" .. msg .. "\".")
        return
    end
    J:Open(J.inside or J.cur)
end

-- ==================================================================== Live
do
----------------------------------------------------------------------
-- Live.lua — where you are and how far you got, inside the dungeon.
--
-- The game gives addons no position inside instances, so "where" comes from what you
-- can see:
--   near    a boss whose nameplate (or your target / mouseover) is up right now. Its number
--           lights up on the map; after it leaves view it stays "last near" for a minute.
--   killed  a boss seen dead (nameplate / target / mouseover), the end of its encounter
--           (ENCOUNTER_END, when Forever sends it), or its body looted. Killed bosses dim
--           on the map and in the tabs. Kept for this run: a reload or a corpse run keeps
--           it; another dungeon or 3 hours later starts a new run.
--   next    the first boss in the path order that isn't killed (rares and optional NPCs
--           don't count).
-- No combat log is read: only units the game shows you.
----------------------------------------------------------------------
local _, ns = ...
local J = ns.J

local NEAR_KEEP = 60          -- "last near" for this long after the boss leaves view
local RUN_MAX = 3 * 3600      -- a run older than this starts over

local function secret(v) return issecretvalue and issecretvalue(v) end

local function npcOf(unit)
    local g = UnitGUID(unit)
    if not g or secret(g) then return nil end
    local kind, _, _, _, _, id = strsplit("-", g)
    if kind ~= "Creature" and kind ~= "Vehicle" then return nil end
    return tonumber(id)
end

-- The dungeon's boss rows by NPC id and by plain name.
local idx = { d = nil, byNpc = {}, byName = {} }
local function plain(s) return (s or ""):gsub("%s*[(<].*$", ""):lower() end
local function index()
    local d = J.inside
    if idx.d == d then return idx end
    idx = { d = d, byNpc = {}, byName = {} }
    for _, key in ipairs(d and d.maps or {}) do
        for _, r in ipairs(ns.Atlas[key].rows) do
            if r[3] == "b" or r[3] == "i" then
                r.mapKey = key
                if r.npc then idx.byNpc[r.npc] = r end
                idx.byName[plain(r[2])] = idx.byName[plain(r[2])] or r
            end
        end
    end
    return idx
end

local function rowOf(unit)
    if not J.inside then return nil end
    local i = index()
    local id = npcOf(unit)
    if id and i.byNpc[id] then return i.byNpc[id] end
    local n = UnitName(unit)
    if n and not secret(n) then return i.byName[plain(n)] end
end

local inView = {}      -- unit token -> row: bosses you can see right now (see Near below)
local plates = {}      -- nameplate tokens up right now, readable or not (re-checked on health)

----------------------------------------------------------------------
-- The run: killed bosses
----------------------------------------------------------------------
-- Runs are per character: VoidDungeonDB.runs["Name-Realm"] (an alt in the same dungeon must
-- not inherit your kills, nor wipe your run; Astra review). The old shared db.run is dropped.
local function me()
    local n, r = UnitName("player"), GetRealmName()
    return (n or "?") .. "-" .. (r or "?")
end

local function current()
    local db = VoidDungeonDB
    if not db then return nil end
    db.run = nil
    db.runs = db.runs or {}
    return db.runs[me()]
end

local function run()
    local db = VoidDungeonDB
    if not db then return nil end
    local r = current()
    local d = J.inside
    if not d then return r end
    if not r or r.dungeon ~= d.name or time() - (r.started or 0) > RUN_MAX then
        r = { dungeon = d.name, started = time(), killed = {} }
        db.runs[me()] = r
    end
    return r
end

local function keyOf(row) return row.npc and ("n" .. row.npc) or ("s" .. plain(row[2])) end

function J:IsKilled(row)
    local r = current()
    return r and self.cur and r.dungeon == self.cur.name and r.killed[keyOf(row)] or false
end

local function killed(row)
    local r = run()
    if not (r and row) or r.killed[keyOf(row)] then return end
    r.killed[keyOf(row)] = true
    -- a confirmed kill isn't "near" any more: dim it now, not a minute later (Astra review)
    if J.near == row then J.near = nil end
    for unit, rr in pairs(inView) do
        if rr == row then inView[unit] = nil end
    end
    J:Changed("live")
end

-- A new run on purpose (the Path tab's "Start a new run").
function J:NewRun()
    if VoidDungeonDB and VoidDungeonDB.runs then VoidDungeonDB.runs[me()] = nil end
    run()
    self:Changed("live")
end

-- The next boss: first main boss (not rare) in path order that isn't killed.
function J:NextBoss()
    if not self.cur then return nil end
    for _, key in ipairs(self.cur.maps) do
        for _, r in ipairs(ns.Atlas[key].rows) do
            if r[3] == "b" and r.npc and not r.rare and not self:IsKilled(r) then return r, key end
        end
    end
end

----------------------------------------------------------------------
-- Near: bosses in view
----------------------------------------------------------------------
J.near, J.nearAt = nil, 0

local function recompute()
    local best
    for unit, r in pairs(inView) do
        -- target / mouseover entries go stale when that unit changes or goes away
        if (unit == "target" or unit == "mouseover")
            and (not UnitExists(unit) or UnitIsDead(unit) or rowOf(unit) ~= r) then
            inView[unit] = nil
        elseif not J:IsKilled(r) then
            best = best or r
        end
    end
    if J.near and J:IsKilled(J.near) then J.near = nil; J:Changed("live") end
    if best then
        if J.near ~= best then
            J.near = best
            -- the boss is on another map of this dungeon (an entrance map, upper level): show it
            if J.mode and best.mapKey and best.mapKey ~= J.map and J.cur == J.inside then J:ShowMap(best.mapKey) end
            J:Changed("live")
        end
        J.nearAt = GetTime()
    elseif J.near and GetTime() - J.nearAt > NEAR_KEEP then
        J.near = nil
        J:Changed("live")
    end
end

local function look(unit)
    local row = rowOf(unit)
    if not row then inView[unit] = nil return end
    if UnitIsDead(unit) then
        inView[unit] = nil
        killed(row)
    else
        inView[unit] = row
    end
end

local ev = CreateFrame("Frame")
ev:RegisterEvent("NAME_PLATE_UNIT_ADDED")
ev:RegisterEvent("NAME_PLATE_UNIT_REMOVED")
ev:RegisterEvent("PLAYER_TARGET_CHANGED")
ev:RegisterEvent("UPDATE_MOUSEOVER_UNIT")
ev:RegisterEvent("UNIT_HEALTH")
ev:RegisterEvent("ENCOUNTER_END")
ev:RegisterEvent("LOOT_OPENED")
ev:RegisterEvent("PLAYER_ENTERING_WORLD")
ev:SetScript("OnEvent", function(_, event, a1, a2, _, _, a5)
    if event == "PLAYER_ENTERING_WORLD" then
        wipe(inView)
        wipe(plates)
        J.near = nil
        if J.inside then run() end
        return
    end
    if not J.inside then return end
    if event == "NAME_PLATE_UNIT_ADDED" then
        plates[a1] = true
        look(a1)
    elseif event == "NAME_PLATE_UNIT_REMOVED" then
        plates[a1] = nil
        local row = inView[a1]
        inView[a1] = nil
        -- a boss plate that vanished at 0 health died out of view of the event
        if row and UnitExists(a1) and UnitIsDead(a1) then killed(row) end
    elseif event == "PLAYER_TARGET_CHANGED" then
        look("target")
    elseif event == "UPDATE_MOUSEOVER_UNIT" then
        look("mouseover")         -- a living boss under the mouse is near too (Astra review)
    elseif event == "UNIT_HEALTH" then
        -- every plate that's up, also one that was unreadable (secret) when it appeared and
        -- may be readable now (Astra review)
        if a1 == "target" or a1 == "mouseover" or plates[a1] then look(a1) end
    elseif event == "ENCOUNTER_END" then
        -- encounterID, name, difficulty, size, success
        if a5 == 1 and a2 and not secret(a2) then
            local row = index().byName[plain(a2)]
            if row then killed(row) end
        end
    elseif event == "LOOT_OPENED" then
        -- every slot, every source (area loot mixes trash and the boss; Astra review)
        if GetLootSourceInfo and GetNumLootItems then
            for slot = 1, GetNumLootItems() do
                local src = { GetLootSourceInfo(slot) }      -- guid1, count1, guid2, count2, ...
                for k = 1, #src, 2 do
                    local g = src[k]
                    if type(g) == "string" and not secret(g) then
                        local _, _, _, _, _, id = strsplit("-", g)
                        local row = index().byNpc[tonumber(id or "")]
                        if row then killed(row) end
                    end
                end
            end
        end
    end
    recompute()
end)

-- keep "last near" expiring even when nothing happens
C_Timer.NewTicker(5, function() if J.inside and J.near then recompute() end end)

